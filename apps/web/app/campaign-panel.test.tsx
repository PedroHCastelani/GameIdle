import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { CampaignPanel } from './campaign-panel';
import { MissionClock } from './mission-clock';
import { gameApi, type Adventure } from '../services/game';
vi.mock('../services/game', () => ({ gameApi: { buy: vi.fn(), item: vi.fn(), challenge: vi.fn() } }));
afterEach(() => { cleanup(); vi.useRealTimers(); vi.resetAllMocks(); });
const chapter = { chapter: 1, name: 'Operação Teste', level: 2, power: 25, gold: 100, exp: 200, reward: 'reward', stages: ['Pistas', 'Entrada', 'Conclusão'] };
const adventure: Adventure = { chapter: 0, completed: false, ending: 'Cidade salva.', power: 20, skillName: 'Medicina', skillLevel: 1, cycles: 0, stamina: 10, staminaNextAt: null, nextLevelExperience: '400', chapters: [chapter], shop: [{ id: 'tool', name: 'Kit', slot: 'WEAPON', power: 6, price: 50, level: 1, sell: 20, description: 'Ferramenta de teste' }], inventory: [], history: [] };
const props = { characterId: 'char', level: 2, gold: '100', busy: false, act: async (action: () => Promise<void>) => action(), refresh: vi.fn(async () => {}), notify: vi.fn() };
it('guides preparation, shows risk and executes a challenge with request identity', async () => {
  vi.mocked(gameApi.challenge).mockResolvedValue({ message: 'Resultado registrado' });
  render(<CampaignPanel {...props} adventure={adventure} />);
  expect(screen.getByText(/Você precisa de 25/)).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Preparar Operação Teste' }));
  expect(screen.getByText(/tentativa vai falhar/)).toBeTruthy();
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Iniciar operação (1 stamina)' })); });
  expect(gameApi.challenge).toHaveBeenCalledWith('char', 1, expect.stringMatching(/^[0-9a-f-]{36}$/));
  expect(props.notify).toHaveBeenCalledWith('Resultado registrado');
});
it('buys, equips, removes and sells with visible inventory feedback', async () => {
  vi.mocked(gameApi.buy).mockResolvedValue({ message: 'Comprado' }); vi.mocked(gameApi.item).mockResolvedValue({ message: 'Atualizado' });
  const { rerender } = render(<CampaignPanel {...props} adventure={adventure} />);
  fireEvent.click(screen.getByRole('button', { name: 'Loja' }));
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Comprar Kit' })); });
  expect(gameApi.buy).toHaveBeenCalledWith('char', 'tool');
  fireEvent.click(screen.getByRole('button', { name: 'Inventário' }));
  expect(screen.getByText(/inventário está vazio/)).toBeTruthy();
  const item = { id: 'item', name: 'Kit', description: 'Útil', quantity: 1, equipped: false, slot: 'WEAPON', power: 6, level: 1, sell: 20, rarity: 'COMMON' };
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, inventory: [item] }} />);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Equipar Kit' })); });
  expect(gameApi.item).toHaveBeenCalledWith('char', 'item', 'equip');
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, inventory: [{ ...item, equipped: true }] }} />);
  expect((screen.getByRole('button', { name: /Vender Kit/ }) as HTMLButtonElement).disabled).toBe(true);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Remover Kit' })); });
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, inventory: [{ ...item, slot: null, quantity: 2 }] }} />);
  await act(async () => { fireEvent.click(screen.getByRole('button', { name: /Vender Kit/ })); });
  expect(gameApi.item).toHaveBeenCalledWith('char', 'item', 'sell');
});
it('shows progression gates, history outcomes and campaign completion', () => {
  const { rerender } = render(<CampaignPanel {...props} level={1} adventure={adventure} />);
  expect(screen.getByText(/até o nível 2/)).toBeTruthy();
  expect((screen.getByRole('button', { name: 'Preparar Operação Teste' }) as HTMLButtonElement).disabled).toBe(true);
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, power: 30 }} />);
  expect(screen.getByText(/Você está pronto/)).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Diário' }));
  expect(screen.getByText(/Nenhuma operação/)).toBeTruthy();
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, history: [{ id: 'history', name: 'Tentativa', outcome: 'FAILED', gold: '0', exp: '0', stages: [{ number: 1, outcome: 'FAILED' }] }, { id: 'win', name: 'Vitória', outcome: 'BOSS_DEFEATED', gold: '100', exp: '200', stages: [{ number: 1, outcome: 'SUCCESS' }] }] }} />);
  expect(screen.getByText(/Operação interrompida/)).toBeTruthy(); expect(screen.getByText(/poder insuficiente/)).toBeTruthy();
  rerender(<CampaignPanel {...props} adventure={{ ...adventure, chapter: 3, completed: true }} />);
  fireEvent.click(screen.getByRole('button', { name: 'Jornada' }));
  expect(screen.getByText('Campanha concluída!')).toBeTruthy(); expect(screen.getByText('Cidade salva.')).toBeTruthy();
});
it('shows cycle countdown, readiness and resets when the cursor changes', () => {
  vi.useFakeTimers();
  const now = new Date().toISOString();
  const { rerender } = render(<MissionClock since={now} serverTime={now} duration={10} />);
  expect(screen.getByText(/Próxima coleta em 10s/)).toBeTruthy();
  act(() => { vi.advanceTimersByTime(11000); });
  expect(screen.getByText(/Progresso pronto/)).toBeTruthy();
  rerender(<MissionClock since="invalid" serverTime="invalid" duration={10} />);
  expect(screen.getByText(/Próxima coleta em 10s/)).toBeTruthy();
});
